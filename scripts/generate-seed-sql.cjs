// scripts/generate-seed-sql.cjs
// Reads the local JSON exports under .dv-tools/data/ (the same ones used for the
// original Dataverse migration — never a live SharePoint call) and generates
// supabase/seed.sql: plain INSERT statements to paste into the Supabase SQL
// Editor. Assigns fresh UUIDs and resolves every parent/child relationship by
// the natural-key text fields already present in the exports (IdCursoText,
// IdUnidadText, IdSesionText, IdConsignaText, IdListaText, IdEscalaText).
//
// Usage: node scripts/generate-seed-sql.cjs

const fs = require('fs')
const path = require('path')
const crypto = require('crypto')

const DATA_DIR = path.join(__dirname, '..', '.dv-tools', 'data')
const OUT_FILE = path.join(__dirname, '..', 'supabase', 'seed.sql')

const load = name => JSON.parse(fs.readFileSync(path.join(DATA_DIR, name), 'utf8'))

// ── SQL literal helpers ──────────────────────────────────────────────────────

const str = v => {
  if (v === null || v === undefined) return 'NULL'
  return `'${String(v).replace(/'/g, "''")}'`
}
const num = v => {
  if (v === null || v === undefined || v === '') return 'NULL'
  const n = Number(v)
  return Number.isFinite(n) ? String(n) : 'NULL'
}
const bool = v => (v === null || v === undefined ? 'NULL' : v ? 'true' : 'false')
const uuid = v => (v ? `'${v}'` : 'NULL')

const newId = () => crypto.randomUUID()

const insert = (table, columns, rows) => {
  if (rows.length === 0) return ''
  const values = rows.map(r => `  (${columns.map(c => r[c]).join(', ')})`).join(',\n')
  return `insert into ${table} (${columns.join(', ')}) values\n${values};\n\n`
}

// ── Load raw exports ──────────────────────────────────────────────────────────

const cursos = load('cursos.json')
const unidades = load('unidades.json')
const sesiones = load('sesiones.json')
const consignas = load('consignas.json')
const rubricas = load('rubricas.json')
const rubricaCriterios = load('rubrica_criterios.json')
const matrices = load('matrices.json')
const matrizPreguntas = load('matriz_preguntas.json')
const listas = load('listas.json')
const listaIndicadores = load('lista_indicadores.json')
const escalas = load('escalas.json')
const escalaIndicadores = load('escala_indicadores.json')

let sql = `-- Diseña+ — seed data generated from .dv-tools/data/*.json (local exports).
-- Run supabase/schema.sql first, then this file, in the Supabase SQL Editor.
-- Generated by scripts/generate-seed-sql.cjs — do not edit by hand.

`

// ── Curso ────────────────────────────────────────────────────────────────────

const cursoIdByText = new Map()
const cursoRows = cursos.map(c => {
  const id = newId()
  cursoIdByText.set(c.IdCursoText, id)
  return {
    dpl_cursoid: uuid(id),
    dpl_nombrecurso: str(c.NombreCurso),
    dpl_idcursotext: str(c.IdCursoText),
    dpl_codigocatalogo: str(c.CodigoCatalogo),
    dpl_carrera: str(c.Carrera),
    dpl_tipoensenanza: str(c.TipoEnsenanza),
    dpl_ciclo: num(c.Ciclo),
    dpl_logrocurso: str(c.LogroCurso),
    dpl_permiteconsignas: bool(c.PermiteConsignas),
    dpl_permiterubricas: bool(c.PermiteRubricas),
    dpl_permitematrizsn: bool(c.PermiteMatrizSN),
    dpl_permitelistacotejo: bool(c.PermiteListaCotejo),
    dpl_permiteescala: bool(c.PermiteEscala),
  }
})
sql += insert(
  'dpl_curso',
  [
    'dpl_cursoid', 'dpl_nombrecurso', 'dpl_idcursotext', 'dpl_codigocatalogo', 'dpl_carrera',
    'dpl_tipoensenanza', 'dpl_ciclo', 'dpl_logrocurso', 'dpl_permiteconsignas', 'dpl_permiterubricas',
    'dpl_permitematrizsn', 'dpl_permitelistacotejo', 'dpl_permiteescala',
  ],
  cursoRows,
)

// ── Unidad ───────────────────────────────────────────────────────────────────

const unidadIdByText = new Map()
const unidadRows = unidades.map(u => {
  const id = newId()
  unidadIdByText.set(u.IdUnidadText, id)
  return {
    dpl_unidadid: uuid(id),
    dpl_nombreunidad: str(u.NombreUnidad),
    dpl_idunidadtext: str(u.IdUnidadText),
    dpl_numerounidad: num(u.NumeroUnidad),
    dpl_logroespecifico: str(u.LogroEspecifico),
    dpl_cursoid: uuid(cursoIdByText.get(u.IdCursoText)),
  }
})
sql += insert(
  'dpl_unidad',
  ['dpl_unidadid', 'dpl_nombreunidad', 'dpl_idunidadtext', 'dpl_numerounidad', 'dpl_logroespecifico', 'dpl_cursoid'],
  unidadRows,
)

// ── Sesión ───────────────────────────────────────────────────────────────────

const sesionIdByText = new Map()
const sesionRows = sesiones.map(s => {
  const id = newId()
  sesionIdByText.set(s.IdSesionText, id)
  return {
    dpl_sesionid: uuid(id),
    dpl_elemento: str(s.Elemento),
    dpl_idsesiontext: str(s.IdSesionText),
    dpl_abreviatura: str(s.Abreviatura),
    dpl_tema: str(s.Tema),
    dpl_unidadid: uuid(unidadIdByText.get(s.IdUnidadText)),
  }
})
sql += insert(
  'dpl_sesion',
  ['dpl_sesionid', 'dpl_elemento', 'dpl_idsesiontext', 'dpl_abreviatura', 'dpl_tema', 'dpl_unidadid'],
  sesionRows,
)

// ── Consigna ─────────────────────────────────────────────────────────────────

sql += insert(
  'dpl_consigna',
  [
    'dpl_consignaid', 'dpl_idconsignatext', 'dpl_queseevaluara', 'dpl_indicaciongeneral',
    'dpl_indicacionesespecificas', 'dpl_recomendaciones', 'dpl_anexo', 'dpl_estado',
    'dpl_activado', 'dpl_usuarioregistro', 'dpl_sesionid',
  ],
  consignas.map(c => ({
    dpl_consignaid: uuid(newId()),
    dpl_idconsignatext: str(c.IdConsignaText),
    dpl_queseevaluara: str(c.QueSeEvaluara),
    dpl_indicaciongeneral: str(c.IndicacionGeneral),
    dpl_indicacionesespecificas: str(c.IndicacionesEspecificas),
    dpl_recomendaciones: str(c.Recomendaciones),
    dpl_anexo: str(c.Anexo),
    dpl_estado: str(c.Estado),
    dpl_activado: bool(c.Activado),
    dpl_usuarioregistro: str(c.UsuarioRegistro),
    dpl_sesionid: uuid(sesionIdByText.get(c.IdSesionText)),
  })),
)

// ── Rúbrica + Criterio ─────────────────────────────────────────────────────
// rubrica_criterios.json has no dedicated rubric id — it shares the parent
// rubric's IdConsignaText composite key, so that's what links child to header.

const rubricaIdByConsignaText = new Map()
const rubricaRows = rubricas.map(r => {
  const id = newId()
  rubricaIdByConsignaText.set(r.IdConsignaText, id)
  return {
    dpl_rubricaid: uuid(id),
    dpl_nombre: str(r.Nombre),
    dpl_estado: str(r.Estado),
    dpl_activado: bool(r.Activado),
    dpl_usuarioregistro: str(r.UsuarioRegistro),
    dpl_sesionid: uuid(sesionIdByText.get(r.IdSesionText)),
  }
})
sql += insert(
  'dpl_rubrica',
  ['dpl_rubricaid', 'dpl_nombre', 'dpl_estado', 'dpl_activado', 'dpl_usuarioregistro', 'dpl_sesionid'],
  rubricaRows,
)

sql += insert(
  'dpl_rubricacriterio',
  [
    'dpl_rubricacriterioid', 'dpl_criterio', 'dpl_orden', 'dpl_definicioncriterio', 'dpl_estandaresperado',
    'dpl_puntajeestandar', 'dpl_enproceso2', 'dpl_puntajeenproceso2', 'dpl_enproceso1', 'dpl_puntajeenproceso1',
    'dpl_inicial', 'dpl_puntajeinicial', 'dpl_rubricaid',
  ],
  rubricaCriterios.map(c => ({
    dpl_rubricacriterioid: uuid(newId()),
    dpl_criterio: str(c.Criterio),
    dpl_orden: num(c.Orden),
    dpl_definicioncriterio: str(c.DefinicionCriterio),
    dpl_estandaresperado: str(c.EstandarEsperado),
    dpl_puntajeestandar: num(c.PuntajeEstandar),
    dpl_enproceso2: str(c.EnProceso2),
    dpl_puntajeenproceso2: num(c.PuntajeEnProceso2),
    dpl_enproceso1: str(c.EnProceso1),
    dpl_puntajeenproceso1: num(c.PuntajeEnProceso1),
    dpl_inicial: str(c.Inicial),
    dpl_puntajeinicial: num(c.PuntajeInicial),
    dpl_rubricaid: uuid(rubricaIdByConsignaText.get(c.IdConsignaText)),
  })),
)

// ── Matriz + Pregunta ──────────────────────────────────────────────────────

const matrizIdByConsignaText = new Map()
const matrizRows = matrices.map(m => {
  const id = newId()
  matrizIdByConsignaText.set(m.IdConsignaText, id)
  return {
    dpl_matrizid: uuid(id),
    dpl_nombre: str(m.Nombre),
    dpl_estado: str(m.Estado),
    dpl_activado: bool(m.Activado),
    dpl_usuarioregistro: str(m.UsuarioRegistro),
    dpl_sesionid: uuid(sesionIdByText.get(m.IdSesionText)),
  }
})
sql += insert(
  'dpl_matriz',
  ['dpl_matrizid', 'dpl_nombre', 'dpl_estado', 'dpl_activado', 'dpl_usuarioregistro', 'dpl_sesionid'],
  matrizRows,
)

sql += insert(
  'dpl_matrizpregunta',
  [
    'dpl_matrizpreguntaid', 'dpl_ejetematico', 'dpl_orden', 'dpl_taxonomia', 'dpl_tipoitem',
    'dpl_plataforma', 'dpl_cantidaditems', 'dpl_puntajeia', 'dpl_matrizid',
  ],
  matrizPreguntas.map(p => ({
    dpl_matrizpreguntaid: uuid(newId()),
    dpl_ejetematico: str(p.EjeTematico),
    dpl_orden: num(p.Orden),
    dpl_taxonomia: str(p.Taxonomia),
    dpl_tipoitem: str(p.TipoItem),
    dpl_plataforma: str(p.Plataforma),
    dpl_cantidaditems: num(p.CantidadItems),
    dpl_puntajeia: num(p.PuntajeIA),
    dpl_matrizid: uuid(matrizIdByConsignaText.get(p.IdConsignaText)),
  })),
)

// ── Lista de Cotejo + Indicador ────────────────────────────────────────────

const listaIdByListaText = new Map()
const listaRows = listas.map(l => {
  const id = newId()
  listaIdByListaText.set(l.IdListaText, id)
  return {
    dpl_listacotejoid: uuid(id),
    dpl_nombre: str(l.Nombre),
    dpl_estado: str(l.Estado),
    dpl_activado: bool(l.Activado),
    dpl_sesionid: uuid(sesionIdByText.get(l.IdSesionText)),
  }
})
sql += insert(
  'dpl_listacotejo',
  ['dpl_listacotejoid', 'dpl_nombre', 'dpl_estado', 'dpl_activado', 'dpl_sesionid'],
  listaRows,
)

// dpl_respuesta mirrors the original Dataverse picklist: 100000000 = Sí, 100000001 = No.
const respuestaToPicklist = v => {
  if (v === null || v === undefined || v === '') return 'NULL'
  const normalized = String(v).trim().toLowerCase()
  if (normalized === 'si' || normalized === 'sí' || normalized === 'true') return '100000000'
  if (normalized === 'no' || normalized === 'false') return '100000001'
  return 'NULL'
}

sql += insert(
  'dpl_listacotejoindicador',
  ['dpl_listacotejoindicadorid', 'dpl_indicador', 'dpl_orden', 'dpl_puntaje', 'dpl_respuesta', 'dpl_observaciones', 'dpl_listacotejoid'],
  listaIndicadores.map(i => ({
    dpl_listacotejoindicadorid: uuid(newId()),
    dpl_indicador: str(i.Indicador),
    dpl_orden: num(i.Orden),
    dpl_puntaje: num(i.Puntaje),
    dpl_respuesta: respuestaToPicklist(i.Respuesta),
    dpl_observaciones: str(i.Observaciones),
    dpl_listacotejoid: uuid(listaIdByListaText.get(i.IdListaText)),
  })),
)

// ── Escala de Valoración + Indicador ───────────────────────────────────────

const escalaIdByEscalaText = new Map()
const escalaRows = escalas.map(e => {
  const id = newId()
  escalaIdByEscalaText.set(e.IdEscalaText, id)
  return {
    dpl_escalavaloracionid: uuid(id),
    dpl_nombre: str(e.Nombre),
    dpl_estado: str(e.Estado),
    dpl_activado: bool(e.Activado),
    dpl_sesionid: uuid(sesionIdByText.get(e.IdSesionText)),
  }
})
sql += insert(
  'dpl_escalavaloracion',
  ['dpl_escalavaloracionid', 'dpl_nombre', 'dpl_estado', 'dpl_activado', 'dpl_sesionid'],
  escalaRows,
)

sql += insert(
  'dpl_escalaindicador',
  [
    'dpl_escalaindicadorid', 'dpl_indicador', 'dpl_orden', 'dpl_puntajeexcelente', 'dpl_puntajebueno',
    'dpl_puntajeregular', 'dpl_puntajeconerrores', 'dpl_puntajenoevidenciado', 'dpl_observaciones',
    'dpl_escalavaloracionid',
  ],
  escalaIndicadores.map(i => ({
    dpl_escalaindicadorid: uuid(newId()),
    dpl_indicador: str(i.Indicador),
    dpl_orden: num(i.Orden),
    dpl_puntajeexcelente: num(i.PuntajeExcelente),
    dpl_puntajebueno: num(i.PuntajeBueno),
    dpl_puntajeregular: num(i.PuntajeRegular),
    dpl_puntajeconerrores: num(i.PuntajeConErrores),
    dpl_puntajenoevidenciado: num(i.PuntajeNoEvidenciado),
    dpl_observaciones: str(i.Observaciones),
    dpl_escalavaloracionid: uuid(escalaIdByEscalaText.get(i.IdEscalaText)),
  })),
)

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true })
fs.writeFileSync(OUT_FILE, sql, 'utf8')

const counts = {
  curso: cursoRows.length,
  unidad: unidadRows.length,
  sesion: sesionRows.length,
  consigna: consignas.length,
  rubrica: rubricaRows.length,
  rubricaCriterio: rubricaCriterios.length,
  matriz: matrizRows.length,
  matrizPregunta: matrizPreguntas.length,
  listaCotejo: listaRows.length,
  listaIndicador: listaIndicadores.length,
  escalaValoracion: escalaRows.length,
  escalaIndicador: escalaIndicadores.length,
}
console.log(`Wrote ${OUT_FILE}`)
console.log(counts)
console.log('Total rows:', Object.values(counts).reduce((a, b) => a + b, 0))
